    private void DisplayStudentScheduleDisplayButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DisplayStudentScheduleDisplayButtonActionPerformed
        // TODO add your handling code here:
        if (currentSemester == null || currentSemester.trim().isEmpty() || currentSemester.equals("None")) {
            return;
        }

        if (SelectStudentScheduleComboBox.getSelectedItem() == null) {
            return;
        }

        String selectedStudent = SelectStudentScheduleComboBox.getSelectedItem().toString();
        String studentID = selectedStudent.split(" ")[0];

        ArrayList<ScheduleEntry> scheduleList =
                ScheduleQueries.getScheduleByStudent(currentSemester, studentID);

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        for (ScheduleEntry entry : scheduleList) {
            model.addRow(new Object[] {
                entry.getCourseCode(),
                entry.getStatus()
            });
        }
    }//GEN-LAST:event_DisplayStudentScheduleDisplayButtonActionPerformed

