    private void addStudentSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addStudentSubmitButtonActionPerformed
        // TODO add your handling code here:
        String studentID = addStudentIDTextField.getText().trim();
        String firstName = addFirstNameTextField.getText().trim();
        String lastName = addLastNameTextField.getText().trim();

        if (studentID.isEmpty() || firstName.isEmpty() || lastName.isEmpty()) {
            addStudentStatusLabel.setText("Please fill in all student fields.");
            return;
        }

        StudentEntry student = new StudentEntry(studentID, firstName, lastName);
        boolean added = StudentQueries.addStudent(student);

        if (added) {
            addStudentStatusLabel.setText(lastName+","+firstName + " has been added.");
            rebuildStudentComboBoxes();
        } else {
            addStudentStatusLabel.setText("Student could not be added.");
        }
    }//GEN-LAST:event_addStudentSubmitButtonActionPerformed

