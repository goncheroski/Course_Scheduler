    private void ScheduleClassSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ScheduleClassSubmitButtonActionPerformed
        if (currentSemester == null || currentSemester.trim().isEmpty() || currentSemester.equals("None")) {
            ScheduleClassStatusLabel.setText("Please select a semester first.");
            return;
        }

        if (SelectClassComboBox.getSelectedItem() == null) {
            ScheduleClassStatusLabel.setText("Please select a class.");
            return;
        }

        if (SelectStudentComboBox.getSelectedItem() == null) {
            ScheduleClassStatusLabel.setText("Please select a student.");
            return;
        }

        String courseCode = SelectClassComboBox.getSelectedItem().toString();
        String selectedStudent = SelectStudentComboBox.getSelectedItem().toString();
        String studentID = selectedStudent.split(" ")[0];

        if (studentHasClass(currentSemester, studentID, courseCode)) {
            ScheduleClassStatusLabel.setText(studentID + " is already scheduled or waitlisted for " + courseCode + ".");
            return;
        }

        int seats = ClassQueries.getClassSeats(currentSemester, courseCode);
        int scheduledCount = ScheduleQueries.getScheduledStudentCount(currentSemester, courseCode);

        String status;
        if (scheduledCount < seats) {
            status = "S";
        } else {
            status = "W";
        }

        java.sql.Timestamp timestamp =
                new java.sql.Timestamp(Calendar.getInstance().getTime().getTime());

        ScheduleEntry entry = new ScheduleEntry(
                currentSemester,
                courseCode,
                studentID,
                status,
                timestamp
        );

        ScheduleQueries.addScheduleEntry(entry);

        if (status.equals("S")) {
            ScheduleClassStatusLabel.setText(studentID + " scheduled for " + courseCode);
        } else {
            ScheduleClassStatusLabel.setText(studentID + " waitlisted for " + courseCode);
        }
    }//GEN-LAST:event_ScheduleClassSubmitButtonActionPerformed

