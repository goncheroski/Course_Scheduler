    private void DropStudentSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DropStudentSubmitButtonActionPerformed
        if (DropStudentComboBox.getSelectedItem() == null) {
            DropStudentTextFeild.setText("Please select a student.");
            return;
        }

        String selectedStudent = DropStudentComboBox.getSelectedItem().toString();
        String studentID = selectedStudent.split(" ")[0];

        ArrayList<ScheduleEntry> schedules =
            ScheduleQueries.getAllSchedulesByStudent(studentID);

        String results = "Dropped student " + studentID + ". ";

        for (ScheduleEntry entry : schedules) {

            boolean wasScheduled =
                entry.getStatus().equals("S");

            ScheduleQueries.dropStudentScheduleByCourse(
                entry.getSemester(),
                studentID,
                entry.getCourseCode()
            );

            results += "Removed from "
                + entry.getCourseCode()
                + " ("
                + entry.getSemester()
                + "). ";

            if (wasScheduled) {
                results += promoteWaitlistedStudent(
                    entry.getSemester(),
                    entry.getCourseCode()
                ) + " ";
            }
        }

        if (schedules.isEmpty()) {
            results += "Student was not scheduled or waitlisted for any classes.";
        }

        StudentQueries.dropStudent(studentID);

        DropStudentTextFeild.setText(results);
        DropStudentTextFeild.setCaretPosition(0);

        rebuildStudentComboBoxes();
    }//GEN-LAST:event_DropStudentSubmitButtonActionPerformed
    
