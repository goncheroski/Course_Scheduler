    private void DropClassSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DropClassSubmitButtonActionPerformed
        if (currentSemester == null || currentSemester.trim().isEmpty() || currentSemester.equals("None")) {
            DropClassTextFeild.setText("Please select a semester first.");
            return;
        }

        if (DropClassComboBox.getSelectedItem() == null) {
            DropClassTextFeild.setText("Please select a class.");
            return;
        }

        String courseCode = DropClassComboBox.getSelectedItem().toString();
        ArrayList<StudentEntry> scheduledStudents =
            MultiTableQueries.getScheduledStudentsByClass(currentSemester, courseCode);
        ArrayList<StudentEntry> waitlistedStudents =
            MultiTableQueries.getWaitlistedStudentsByClass(currentSemester, courseCode);

        ScheduleQueries.dropScheduleByCourse(
            currentSemester,
            courseCode
        );

        ClassQueries.dropClass(
            currentSemester,
            courseCode
        );

        String results = courseCode + " has been dropped from " + currentSemester + ".\n";

        for (StudentEntry student : scheduledStudents) {
            results += student.getStudentID() + " removed from scheduled list.\n";
        }

        for (StudentEntry student : waitlistedStudents) {
            results += student.getStudentID() + " removed from waitlist.\n";
        }

        if (scheduledStudents.isEmpty() && waitlistedStudents.isEmpty()) {
            results += "No students were scheduled or waitlisted for this class.";
        }

        DropClassTextFeild.setText(results);

        rebuildClassComboBoxes();
    }//GEN-LAST:event_DropClassSubmitButtonActionPerformed

    private void StudentDropClassSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_StudentDropClassSubmitButtonActionPerformed
        if (currentSemester == null || currentSemester.trim().isEmpty() || currentSemester.equals("None")) {
            StudentDropClassTextFeild.setText("Please select a semester first.");
            return;
        }

        if (StudentDropClassStudentComboBox.getSelectedItem() == null) {
            StudentDropClassTextFeild.setText("Please select a student.");
            return;
        }

        if (StudentDropClassClassComboBox.getSelectedItem() == null) {
            StudentDropClassTextFeild.setText("Please select a class.");
            return;
        }

        String selectedStudent = StudentDropClassStudentComboBox.getSelectedItem().toString();
        String studentID = selectedStudent.split(" ")[0];
        String courseCode = StudentDropClassClassComboBox.getSelectedItem().toString();

        ArrayList<ScheduleEntry> schedules =
            ScheduleQueries.getScheduleByStudent(
                currentSemester,
                studentID
            );

        boolean foundClass = false;
        boolean wasScheduled = false;

        for (ScheduleEntry entry : schedules) {
            if (entry.getCourseCode().equals(courseCode)) {
                foundClass = true;
                wasScheduled = entry.getStatus().equals("S");
                break;
            }
        }

        if (!foundClass) {
            StudentDropClassTextFeild.setText(studentID + " is not scheduled or waitlisted for " + courseCode + ".");
            return;
        }

        ScheduleQueries.dropStudentScheduleByCourse(
            currentSemester,
            studentID,
            courseCode
        );

        String result = studentID + " dropped from " + courseCode + ". ";

        if (wasScheduled) {
            result += promoteWaitlistedStudent(
                currentSemester,
                courseCode
            );
        }

        StudentDropClassTextFeild.setText(result);
        StudentDropClassTextFeild.setCaretPosition(0);
    }//GEN-LAST:event_StudentDropClassSubmitButtonActionPerformed

