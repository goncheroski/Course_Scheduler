    private boolean studentHasClass(String semester, String studentID, String courseCode) {
        ArrayList<ScheduleEntry> schedules = ScheduleQueries.getScheduleByStudent(semester, studentID);

        for (ScheduleEntry entry : schedules) {
            if (entry.getCourseCode().equals(courseCode)) {
                return true;
            }
        }

        return false;
    }
    
    private String promoteWaitlistedStudent(String semester, String courseCode) {
        ArrayList<ScheduleEntry> waitlist = ScheduleQueries.getWaitlistedStudentsByClass(semester, courseCode);

        if (waitlist.size() > 0) {
            ScheduleEntry first = waitlist.get(0);
            java.sql.Timestamp timestamp =
                new java.sql.Timestamp(Calendar.getInstance().getTime().getTime());

            ScheduleEntry updatedEntry = new ScheduleEntry(
                first.getSemester(),
                first.getCourseCode(),
                first.getStudentID(),
                "S",
                timestamp
            );

            ScheduleQueries.updateScheduleEntry(updatedEntry);

            return "Promoted " + first.getStudentID() + " from waitlist to " + courseCode + ".";
        }

        return "No waitlist for " + courseCode + ".";
    }
    
